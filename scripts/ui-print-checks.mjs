import assert from 'node:assert/strict'

/** Disposable profile only. Provider IPC is mocked by test-automation-app. */
export async function runPrintUiChecks(page, { app, call, client, imageId }) {
  await call('navigate', { target: 'print' })
  await page.locator('[data-studio-section="print"][aria-current="page"]').waitFor()
  assert.equal((await call('get_status')).view.section, 'print')
  const source = await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 128; canvas.height = 192
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#325748'; ctx.fillRect(0, 0, 128, 192)
    return window.api.saveImage(canvas.toDataURL('image/png'), 'print-import-fixture.png')
  })
  const printImport = await call('import_media', { source: source.filePath, name: 'Print imported original', importMode: 'print', printFormat: 'a4-portrait' })
  assert.equal(printImport.isPrint, true)
  assert.equal(printImport.printFormat, 'a4-portrait')
  assert.equal(printImport.width, 128)
  assert.equal(printImport.height, 192)
  assert.equal(printImport.mimeType, 'image/png')
  assert.ok((await call('list_images', { mode: 'print' })).images.some(image => image.id === printImport.id))
  assert.ok(!(await call('list_images', { mode: 'image' })).images.some(image => image.id === printImport.id))
  assert.equal((await client.callTool({ name: 'import_media', arguments: { source: source.filePath, printFormat: 'a4-portrait' } })).isError, true)
  const videoSource = (await call('list_images', { mode: 'video', limit: 100 })).images.find(image => image.filePath)
  assert.ok(videoSource, 'Existing disposable video fixture is available')
  assert.equal((await client.callTool({ name: 'import_media', arguments: { source: videoSource.filePath, importMode: 'print' } })).isError, true)
  await page.getByRole('button', { name: 'Import', exact: true }).click()
  await page.locator('#media-import-source').fill(source.filePath)
  await page.getByRole('combobox', { name: 'Print-Importformat', exact: true }).selectOption('business-card')
  await page.getByRole('button', { name: 'Zu Print hinzufügen', exact: true }).click()
  await page.getByRole('dialog', { name: 'Medien importieren' }).waitFor({ state: 'hidden' })
  assert.equal((await call('get_status')).view.section, 'print')
  const humanImport = (await call('list_images', { mode: 'print' })).images.find(image => image.id !== printImport.id && image.model === 'imported' && image.printFormat === 'business-card')
  assert.ok(humanImport, 'Human import stays in Print and is MCP-visible')
  assert.equal(humanImport.width, 128)
  assert.equal(humanImport.height, 192)
  const settings = await call('get_settings')
  const initial = await call('get_draft', { mode: 'print' })
  assert.deepEqual(initial.models, [settings.defaultModel])
  const prompt = 'WEIHNACHTSMARKT. 14. Dezember. Rathausplatz. Use [Image 1] as a small logo.'
  const patch = { prompt, models: ['openai/gpt-image-2.5/sunburst/text-to-image'], printFormat: 'business-card', printStyle: 'swiss', printMetaPrompt: 'Use only pine green and warm ivory.', references: [imageId], collectionIds: [], imageCount: 1 }
  const updated = await call('update_draft', { mode: 'print', patch })
  assert.equal(updated.printFormat, patch.printFormat)
  assert.equal(updated.printStyle, patch.printStyle)
  assert.equal(updated.printMetaPrompt, patch.printMetaPrompt)
  assert.match(updated.systemPrompt, /pine green/)
  assert.equal(updated.references[0].promptReference, '[Image 1]')
  const editor = page.locator('[contenteditable="true"]').last()
  assert.ok((await editor.textContent()).includes('WEIHNACHTSMARKT'))
  await editor.press('End')
  await page.keyboard.type(' Free entry.')
  const live = await call('get_draft', { mode: 'print' })
  assert.match(live.prompt, /Free entry/)
  assert.equal((await call('get_settings')).printPrompt, patch.printMetaPrompt)
  const direct = await call('preview_generation', { mode: 'print', prompt: live.prompt, references: [imageId], presetId: '' })
  assert.equal(direct.request.printFormat, patch.printFormat)
  assert.equal(direct.request.printStyle, patch.printStyle)
  assert.equal(direct.request.systemPrompt, live.systemPrompt)
  assert.equal(direct.request.apiPrompt, live.apiPrompt)
  for (const invalid of [{ printFormat: 'invalid' }, { printStyle: 'wordmark' }]) {
    assert.equal((await client.callTool({ name: 'update_draft', arguments: { mode: 'print', patch: invalid } })).isError, true)
  }
  const submitted = await call('generate_draft', { mode: 'print' })
  await call('wait_for_jobs', { ids: submitted.jobIds, timeoutMs: 20000 })
  const jobs = (await call('get_status', { ids: submitted.jobIds })).jobs
  assert.ok(jobs.every(job => job.status === 'completed' && job.isPrint && job.printFormat === patch.printFormat))
  const printGallery = (await call('list_images', { mode: 'print' })).images
  assert.ok(submitted.jobIds.every(id => printGallery.some(image => image.id === id)))
  assert.ok(!(await call('list_images', { mode: 'image' })).images.some(image => submitted.jobIds.includes(image.id)))
  const details = await call('generation_details', { id: submitted.jobIds[0] })
  assert.equal(details.generationOptions.printMetaPrompt, patch.printMetaPrompt)
  assert.equal(details.generationOptions.apiPrompt, direct.request.apiPrompt)
  const providerCalls = await app.evaluate(() => globalThis.__automationTestCalls)
  assert.ok(providerCalls.some(request => request.kind === 'image' && request.prompt.includes('WEIHNACHTSMARKT')))
  await call('navigate', { target: 'image' })
  await page.locator('[data-studio-section="print"]').click()
  assert.equal((await call('get_status')).view.section, 'print')
  await page.getByRole('combobox', { name: 'Printformat', exact: true }).selectOption('dl-landscape')
  await page.getByTitle('Alle weiteren Einstellungen', { exact: true }).click()
  const lowerFormat = page.getByRole('combobox', { name: 'Printformat in Bildeinstellungen', exact: true })
  assert.equal(await lowerFormat.inputValue(), 'dl-landscape')
  const topFormat = page.getByRole('combobox', { name: 'Printformat', exact: true })
  assert.deepEqual(await lowerFormat.locator('option').evaluateAll(options => options.map(o => o.value)), await topFormat.locator('option').evaluateAll(options => options.map(o => o.value)))
  await lowerFormat.selectOption('business-card-portrait')
  assert.equal(await topFormat.inputValue(), 'business-card-portrait')
  assert.equal((await call('get_draft', { mode: 'print' })).printFormat, 'business-card-portrait')
  assert.equal(await page.getByLabel('Bildbreite in Pixeln', { exact: true }).inputValue(), '992')
  await call('update_draft', { mode: 'print', patch: { printFormat: 'dl-landscape' } })
  assert.equal(await lowerFormat.inputValue(), 'dl-landscape')
  assert.equal(await page.getByLabel('Bildbreite in Pixeln', { exact: true }).inputValue(), '3152')
  assert.equal(await page.getByLabel('Pixel-Seitenverhältnis', { exact: true }).count(), 0)
  await page.waitForTimeout(200)
  await page.screenshot({ path: 'screenshots/print-format-parity.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.getByRole('combobox', { name: 'Print-Gestaltung', exact: true }).selectOption('editorial')
  await page.getByRole('button', { name: 'Gestaltungsregeln', exact: true }).click()
  await page.getByRole('textbox', { name: 'Eigene Print-Gestaltungsregeln', exact: true }).fill('Human-edited art direction.')
  assert.equal((await call('get_draft', { mode: 'print' })).printFormat, 'dl-landscape')
  assert.equal((await call('get_settings')).printPrompt, 'Human-edited art direction.')
  await call('update_settings', { defaultPrintFormat: patch.printFormat, defaultPrintStyle: patch.printStyle, printPrompt: patch.printMetaPrompt })
  const returned = await call('get_draft', { mode: 'print' })
  assert.equal(returned.printMetaPrompt, patch.printMetaPrompt)
  assert.equal(returned.printFormat, patch.printFormat)
  console.log('Print UI/MCP: navigation, settings, references, preview, mocked generation, metadata and gallery passed')
}
